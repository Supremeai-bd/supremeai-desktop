private val BENGALI_UNICODE_REGEX = Regex("[\u0980-\u09FF]")
private val BANGLISH_WORDS_REGEX = Regex(
    "\\b(ami|tumi|apni|kemon|acho|achen|valo|bhalo|koro|korbo|korte|ki|keno|kothay|kobe|hobey|hobe|na|hoy|kore|amar|tomar|apnar|bangla|bhai|apu|doya|kore|bolun|bolo|parbo|lagbe|chai|dao|deben|shukriya|dhonnobad|bujhlam|bujhte)\\b",
    RegexOption.IGNORE_CASE
)

fun detectBengaliOrBanglish(text: String): Boolean {
    if (text.isBlank()) return false
    if (BENGALI_UNICODE_REGEX.containsMatchIn(text)) return true
    return BANGLISH_WORDS_REGEX.findAll(text).count() >= 2
}
